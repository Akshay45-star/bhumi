router.get("/today", requireAuth, async (req: Request, res: Response) => {
  // Day-of-year index (0-364) so every user gets the same prompt on the same day
  const now      = new Date();
  const start    = new Date(now.getFullYear(), 0, 0);
  const diff     = now.getTime() - start.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24)) - 1; // 0-indexed
  const idx      = dayOfYear % PROMPT_BANK.length;
  res.json({ prompt: PROMPT_BANK[idx], dayOfYear });
});

router.get("/bank", requireAuth, async (_req: Request, res: Response) => {
  // Shuffle a deterministic 10-item subset based on today's date seed
  const seed = new Date().toDateString();
  const hashed = seed.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const prompts = [...PROMPT_BANK]
    .sort((a, b) => (a.charCodeAt(0) + hashed) % 7 - (b.charCodeAt(0) + hashed) % 7)
    .slice(0, 10);
  res.json({ prompts });
});

export default router;
